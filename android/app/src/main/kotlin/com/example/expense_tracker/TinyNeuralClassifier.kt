    fun predict(text: String): NeuralPrediction {
        val input = vectorize(text)
        val hidden = FloatArray(HIDDEN_SIZE)

        for (h in 0 until HIDDEN_SIZE) {
            var sum = b1[h]
            for (i in 0 until INPUT_SIZE) {
                val x = input[i]
                if (x != 0f) sum += x * w1[i * HIDDEN_SIZE + h]
            }
            hidden[h] = if (sum > 0f) sum else 0f
        }

        val logits = FloatArray(labels.size)
        var maxLogit = Float.NEGATIVE_INFINITY
        for (o in labels.indices) {
            var sum = b2[o]
            for (h in 0 until HIDDEN_SIZE) sum += hidden[h] * w2[h * labels.size + o]
            logits[o] = sum
            if (sum > maxLogit) maxLogit = sum
        }

        val probs = DoubleArray(labels.size)
        var denom = 0.0
        for (o in labels.indices) {
            probs[o] = exp((logits[o] - maxLogit).toDouble())
            denom += probs[o]
        }
        var best = 0
        for (o in labels.indices) {
            probs[o] /= denom
            if (probs[o] > probs[best]) best = o
        }
        return NeuralPrediction(
            label = labels[best],
            confidence = probs[best],
            probabilities = labels.indices.associate { labels[it] to probs[it] }
        )
    }

    private fun vectorize(message: String): FloatArray {
        val text = message.lowercase(Locale.ROOT)
        val tokens = Regex("[a-z0-9₹]+").findAll(text).map { it.value }.toList()
        val features = ArrayList<String>(tokens.size * 2 + 12)
        features.addAll(tokens)
        for (i in 0 until tokens.size - 1) features.add(tokens[i] + "_" + tokens[i + 1])

        if (listOf("will be debited", "scheduled", "upcoming", "due on", "not yet completed").any { text.contains(it) }) features.add("__future_pending__")
        if (text.contains("otp") || text.contains("one time password")) features.add("__otp__")
        if (listOf("offer", "loan", "apply now").any { text.contains(it) }) features.add("__promo__")
        if (listOf("refund", "refunded", "reversal", "reversed", "returned").any { text.contains(it) }) features.add("__refund__")
        if (listOf("credited", "received", "salary", "cashback").any { text.contains(it) }) features.add("__credit__")
        if (listOf("debited", "paid", "spent", "charged", "sent", "payment successful").any { text.contains(it) }) features.add("__debit__")
        if (listOf("self transfer", "own account", "between your accounts", "internal transfer", "moved between").any { text.contains(it) }) features.add("__transfer__")
        if (listOf("sip", "mutual fund", "zerodha", "groww", "stocks", "stock purchase", "gold investment", "invested").any { text.contains(it) }) features.add("__investment__")
        if (text.contains("upi")) features.add("__upi__")
        if (message.contains("₹") || text.contains("rs") || text.contains("inr")) features.add("__amount_marker__")

        val vector = FloatArray(INPUT_SIZE)
        for (feature in features) {
            val hash = feature.hashCode().toLong()
            val positive = if (hash == Long.MIN_VALUE) 0L else kotlin.math.abs(hash)
            val index = (positive % INPUT_SIZE).toInt()
            vector[index] += 1f
        }

        var sumSquares = 0.0
        for (v in vector) sumSquares += v * v
        val norm = sqrt(sumSquares)
        if (norm > 0.0) {
            for (i in vector.indices) vector[i] = (vector[i] / norm).toFloat()
        }
        return vector
    }
